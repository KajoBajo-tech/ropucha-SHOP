document.addEventListener("DOMContentLoaded", () => {
  // --- ROZPISKA I ZMIANA JĘZYKA ---
  const langSelect = document.getElementById("langSelect");
  let currentLang = "pl";

  function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    langSelect.value = lang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (translations[lang][key]) {
        el.innerHTML = translations[lang][key];
      }
    });

    // Aktualizacja URL hash
    const currentHash = window.location.hash || "#/pl/home";
    const route = currentHash.split("/")[2] || "home";
    window.location.hash = `#/${lang}/${route}`;
  }

  if (langSelect) {
    langSelect.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  }

  // --- PROSTY ROUTING (HASH) ---
  function handleRoute() {
    const hash = window.location.hash || "#/pl/home";
    const parts = hash.replace("#/", "").split("/");
    const lang = parts[0] || "pl";
    const route = parts[1] || "home";

    if (lang !== currentLang) {
      setLanguage(lang);
    }

    // Podświetlenie nawigacji
    document.querySelectorAll(".nav-link").forEach((link) => {
      const linkPath = link.getAttribute("data-path");
      if (linkPath === route) {
        link.classList.add("active");
      } else {
        link.classList.remove("active");
      }
    });

    // Przewinięcie do sekcji jeśli istnieje
    const targetElement = document.getElementById(route);
    if (targetElement) {
      targetElement.scrollIntoView({ behavior: "smooth" });
    }
  }

  window.addEventListener("hashchange", handleRoute);
  handleRoute(); // Inicjalizacja przy starcie

  // --- OBSŁUGA MODALU BETA TESTÓW ---
  const modal = document.getElementById("signupModal");
  const openModalBtn = document.getElementById("openModalBtn");
  const closeModalBtn = document.getElementById("closeModalBtn");
  const signupForm = document.getElementById("signupForm");
  const successMessage = document.getElementById("successMessage");

  if (openModalBtn) {
    openModalBtn.addEventListener("click", () => {
      modal.classList.add("active");
    });
  }

  if (closeModalBtn) {
    closeModalBtn.addEventListener("click", () => {
      modal.classList.remove("active");
    });
  }

  window.addEventListener("click", (e) => {
    if (e.target === modal) {
      modal.classList.remove("active");
    }
  });

  if (signupForm) {
    signupForm.addEventListener("submit", (e) => {
      e.preventDefault();
      signupForm.style.display = "none";
      successMessage.style.display = "block";
    });
  }

  // --- PANEL ADMINISTRATORA & OBSŁUGA OSI CZASU ---
  const adminLoginBtn = document.getElementById("adminLoginBtn");
  const adminPanel = document.getElementById("adminPanel");
  const addStepBtn = document.getElementById("addStepBtn");
  const timelineList = document.getElementById("timelineList");

  // Hasło dostępowe administratora
  const ADMIN_PASSWORD = "ropucha_admin";

  if (adminLoginBtn) {
    adminLoginBtn.addEventListener("click", () => {
      const inputPass = prompt("Podaj hasło administratora:");
      if (inputPass === ADMIN_PASSWORD) {
        alert("Zalogowano jako Administrator!");
        adminPanel.style.display = "block";
      } else if (inputPass !== null) {
        alert("Błędne hasło!");
      }
    });
  }

  if (addStepBtn) {
    addStepBtn.addEventListener("click", () => {
      const titleInput = document.getElementById("newStepTitle");
      const descInput = document.getElementById("newStepDesc");

      if (!titleInput.value.trim() || !descInput.value.trim()) {
        alert("Uzupełnij tytuł i opis!");
        return;
      }

      const totalItems = timelineList.querySelectorAll(".timeline-item").length + 1;

      const newItemHtml = `
        <div class="timeline-item">
          <div class="timeline-node">${totalItems}</div>
          <div class="timeline-content">
            <h4>${titleInput.value.trim()}</h4>
            <p>${descInput.value.trim()}</p>
          </div>
        </div>
      `;

      timelineList.insertAdjacentHTML("beforeend", newItemHtml);
      titleInput.value = "";
      descInput.value = "";
    });
  }
});